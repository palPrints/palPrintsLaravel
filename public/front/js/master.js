(() => {
  "use strict";

  function initializePalPrintsAnimations() {
    if (document.documentElement.dataset.palAnimationsInitialized === "true") {
      return;
    }

    document.documentElement.dataset.palAnimationsInitialized = "true";
    document.body.classList.add("pal-motion-enabled");

    /* إضافة ظل للهيدر عند النزول، بدون شريط تقدم علوي */
    const navbar = document.getElementById("navbar");
    let scrollFrame = 0;

    function updateNavbarOnScroll() {
      scrollFrame = 0;
      navbar?.classList.toggle("pal-navbar-scrolled", window.scrollY > 14);
    }

    function requestNavbarUpdate() {
      if (scrollFrame) return;
      scrollFrame = requestAnimationFrame(updateNavbarOnScroll);
    }

    window.addEventListener("scroll", requestNavbarUpdate, { passive: true });
    updateNavbarOnScroll();

    /* Reveal elements */
    const groups = [
      { selector: ".categories__header", direction: "", step: 0 },
      { selector: ".category-card", direction: "", step: 85 },
      { selector: ".design-discovery__header", direction: "", step: 0 },
      { selector: ".design-discovery__search", direction: "", step: 0 },
      { selector: ".design-category-card", direction: "", step: 70 },
      { selector: ".design-discovery__feature", direction: "", step: 100 },
      { selector: ".section-title", direction: "", step: 0 },
      { selector: ".step-card", direction: "", step: 110 },
      {
        selector: ".designer-banner__left-side",
        direction: "",
        step: 0,
      },
      {
        selector: ".designer-banner__right-side",
        direction: "",
        step: 0,
      },
      { selector: ".testimonials__header", direction: "", step: 0 },
      { selector: ".footer__card", direction: "", step: 0 },
      { selector: ".footer__bottom", direction: "", step: 100 },
    ];

    const revealItems = [];

    groups.forEach(({ selector, direction, step }) => {
      document.querySelectorAll(selector).forEach((element, index) => {
        element.classList.add("pal-reveal");

        if (direction) {
          element.classList.add(direction);
        }

        element.style.setProperty(
          "--pal-delay",
          `${Math.min(index * step, 420)}ms`,
        );

        revealItems.push(element);
      });
    });

    function revealElement(element) {
      if (element.classList.contains("pal-visible")) return;

      element.classList.add("pal-visible");
      element.closest("section, footer")?.classList.add("pal-section-active");

      // Preserve the original reveal duration, then switch the component to
      // the shared hover speed after its entrance has fully completed.
      const revealDelay = Number.parseInt(
        getComputedStyle(element).getPropertyValue("--pal-delay"),
        10,
      ) || 0;

      window.setTimeout(() => {
        element.classList.add("pal-reveal-complete");
      }, revealDelay + 720);
    }

    /* Immediate viewport check prevents any observer/browser edge case. */
    function revealVisibleElements() {
      const viewportTrigger = window.innerHeight * 0.9;

      revealItems.forEach((element) => {
        if (element.classList.contains("pal-visible")) return;

        const box = element.getBoundingClientRect();

        if (box.top < viewportTrigger && box.bottom > 0) {
          revealElement(element);
        }
      });
    }

    let observer = null;

    if ("IntersectionObserver" in window) {
      observer = new IntersectionObserver(
        (entries) => {
          entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            revealElement(entry.target);
            observer?.unobserve(entry.target);
          });
        },
        {
          threshold: 0.08,
          rootMargin: "0px 0px -4% 0px",
        },
      );

      revealItems.forEach((element) => observer.observe(element));
    }

    window.addEventListener("scroll", revealVisibleElements, {
      passive: true,
    });
    window.addEventListener("resize", revealVisibleElements);

    requestAnimationFrame(() => {
      revealVisibleElements();
    });

    /* Safety fallback: no element remains hidden if an observer is blocked. */
    window.setTimeout(() => {
      revealVisibleElements();
    }, 500);

    /* Statistics reveal and counters: start only after the user scrolls. */
    const statsSection = document.querySelector(".stats-section");
    const statNumbers = statsSection
      ? Array.from(
          statsSection.querySelectorAll(".stat-item__number[data-target]"),
        )
      : [];
    const statsTrigger = statNumbers[0]?.closest(".stat-item") || statsSection;
    const reduceStatsMotion = window.matchMedia(
      "(prefers-reduced-motion: reduce)",
    ).matches;
    const statsCounterDuration = reduceStatsMotion ? 900 : 2000;
    let statsAnimationStarted = false;
    let statsObserver = null;

    function statValue(element, value) {
      const prefix = element.dataset.prefix || "";
      const suffix = element.dataset.suffix || "";
      return `${prefix}${value}${suffix}`;
    }

    function setFinalStatNumber(element) {
      const target = Number.parseInt(element.dataset.target || "0", 10);
      element.textContent = statValue(
        element,
        Number.isFinite(target) ? target : 0,
      );
      element.dataset.palCounterDone = "true";
    }

    function animateStatNumber(element, delay) {
      if (element.dataset.palCounterDone === "true") return;

      const target = Number.parseInt(element.dataset.target || "0", 10);

      if (!Number.isFinite(target)) {
        setFinalStatNumber(element);
        return;
      }

      element.dataset.palCounterDone = "true";

      window.setTimeout(() => {
        let startTime = null;

        function draw(now) {
          if (startTime === null) {
            startTime = now;
          }

          const progress = Math.min(
            (now - startTime) / statsCounterDuration,
            1,
          );
          const easedProgress = 1 - Math.pow(1 - progress, 4);
          const value = Math.round(target * easedProgress);

          element.textContent = statValue(element, value);

          if (progress < 1) {
            requestAnimationFrame(draw);
          } else {
            setFinalStatNumber(element);
          }
        }

        requestAnimationFrame(draw);
      }, delay);
    }

    function clearStatsListeners() {
      statsObserver?.disconnect();
      window.removeEventListener("scroll", checkStatsVisibility);
      window.removeEventListener("resize", checkStatsVisibility);
    }

    function revealStatsSection() {
      if (!statsSection || statsAnimationStarted) return;

      statsAnimationStarted = true;
      statsSection.classList.add("is-stats-visible");

      window.setTimeout(() => {
        statsSection.classList.add("stats-hover-ready");
      }, 1500);

      statNumbers.forEach((element, index) => {
        animateStatNumber(element, 340 + index * 150);
      });

      clearStatsListeners();
    }

    function statsReachedTriggerLine() {
      if (!statsTrigger) return false;

      const box = statsTrigger.getBoundingClientRect();
      return (
        box.top <= window.innerHeight * 0.76 &&
        box.bottom >= window.innerHeight * 0.3
      );
    }

    function checkStatsVisibility() {
      if (
        statsAnimationStarted ||
        !statsReachedTriggerLine()
      ) {
        return;
      }

      revealStatsSection();
    }

    if (statsSection) {
      statsSection.classList.remove("is-stats-visible");
      statsSection.classList.add("stats-motion-ready");

      statNumbers.forEach((element) => {
        element.dataset.palCounterDone = "false";
        element.textContent = statValue(element, 0);
      });

      if ("IntersectionObserver" in window && statsTrigger) {
        statsObserver = new IntersectionObserver(
          (entries) => {
            if (entries.some((entry) => entry.isIntersecting)) {
              revealStatsSection();
            }
          },
          {
            threshold: 0.55,
            rootMargin: "0px 0px -6% 0px",
          },
        );

        statsObserver.observe(statsTrigger);
      }

      window.addEventListener("scroll", checkStatsVisibility, {
        passive: true,
      });
      window.addEventListener("resize", checkStatsVisibility);

      requestAnimationFrame(checkStatsVisibility);
    }

    /* Ripple buttons */
    document
      .querySelectorAll(
        ".btn-primary, .btn-hero-primary, .designer-banner__btn",
      )
      .forEach((button) => {
        button.classList.add("pal-ripple-host");

        button.addEventListener("click", (event) => {
          const box = button.getBoundingClientRect();
          const size = Math.max(box.width, box.height) * 2;
          const ripple = document.createElement("span");

          ripple.className = "pal-ripple";
          ripple.style.width = `${size}px`;
          ripple.style.height = `${size}px`;
          ripple.style.left = `${event.clientX - box.left}px`;
          ripple.style.top = `${event.clientY - box.top}px`;

          button.querySelector(".pal-ripple")?.remove();
          button.appendChild(ripple);

          ripple.addEventListener("animationend", () => ripple.remove(), {
            once: true,
          });
        });
      });

    /* A visible class proves initialization in DevTools. */
    console.info("PALPRINTS animations initialized");
  }

  if (document.readyState === "loading") {
    document.addEventListener(
      "DOMContentLoaded",
      initializePalPrintsAnimations,
      { once: true },
    );
  } else {
    initializePalPrintsAnimations();
  }
})();
