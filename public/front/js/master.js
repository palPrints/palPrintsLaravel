(() => {
  "use strict";

  const AUTO_PLAY_DELAY = 5000;

  function initializeTestimonialsCarousel() {
    const section = document.querySelector(".testimonials-section");
    const stage = section?.querySelector(".testimonials__carousel");
    const cards = stage
      ? Array.from(stage.querySelectorAll(".testimonial-card"))
      : [];
    const previousButton = section?.querySelector(
      ".testimonials__nav-btn--prev",
    );
    const nextButton = section?.querySelector(
      ".testimonials__nav-btn--next",
    );
    const dotsContainer = section?.querySelector(".testimonials__dots");
    const currentCounter = section?.querySelector(".testimonials__current");
    const totalCounter = section?.querySelector(".testimonials__total");

    if (
      !section ||
      !stage ||
      cards.length < 2 ||
      stage.dataset.testimonialsInitialized === "true"
    ) {
      return;
    }

    stage.dataset.testimonialsInitialized = "true";

    const reducedMotion = window.matchMedia(
      "(prefers-reduced-motion: reduce)",
    ).matches;
    const dots = [];
    let currentIndex = 0;
    let autoPlayTimer = 0;
    let touchStartX = null;
    let sectionIsVisible = !("IntersectionObserver" in window);

    function normalizedIndex(index) {
      return (index + cards.length) % cards.length;
    }

    function positionName(index) {
      const distance = normalizedIndex(index - currentIndex);

      if (distance === 0) return "active";
      if (distance === 1) return "next";
      if (distance === cards.length - 1) return "prev";
      return "hidden";
    }

    function updateControlLabels() {
      const isEnglish = document.documentElement.lang === "en";
      const previousLabel = isEnglish ? "Previous review" : "الرأي السابق";
      const nextLabel = isEnglish ? "Next review" : "الرأي التالي";

      previousButton?.setAttribute("aria-label", previousLabel);
      nextButton?.setAttribute("aria-label", nextLabel);

      const previousIcon = previousButton?.querySelector("i");
      const nextIcon = nextButton?.querySelector("i");

      if (previousIcon) {
        previousIcon.className = "bi bi-arrow-left";
      }

      if (nextIcon) {
        nextIcon.className = "bi bi-arrow-right";
      }

      dots.forEach((dot, index) => {
        dot.setAttribute(
          "aria-label",
          isEnglish
            ? `Show customer review ${index + 1}`
            : `عرض رأي العميل رقم ${index + 1}`,
        );
      });
    }

    function renderCarousel() {
      cards.forEach((card, index) => {
        const position = positionName(index);
        const isActive = position === "active";

        card.classList.remove("is-active", "is-prev", "is-next", "is-hidden");
        card.classList.add(`is-${position}`);
        card.dataset.carouselPosition = position;
        card.setAttribute("aria-hidden", isActive ? "false" : "true");
        card.setAttribute("aria-label", `${index + 1} / ${cards.length}`);
        card.tabIndex = isActive ? 0 : -1;
        card.inert = position === "hidden";
      });

      dots.forEach((dot, index) => {
        const isActive = index === currentIndex;
        dot.classList.toggle("is-active", isActive);
        dot.setAttribute("aria-current", isActive ? "true" : "false");
      });

      if (currentCounter) currentCounter.textContent = String(currentIndex + 1);
      if (totalCounter) totalCounter.textContent = String(cards.length);
      stage.classList.add("is-ready");
    }

    function stopAutoPlay() {
      if (!autoPlayTimer) return;
      window.clearTimeout(autoPlayTimer);
      autoPlayTimer = 0;
    }

    function startAutoPlay() {
      stopAutoPlay();

      if (reducedMotion || document.hidden || !sectionIsVisible) return;

      autoPlayTimer = window.setTimeout(() => {
        goTo(currentIndex + 1, "next");
      }, AUTO_PLAY_DELAY);
    }

    function goTo(index, direction = "next", restartTimer = true) {
      currentIndex = normalizedIndex(index);
      stage.dataset.direction = direction;
      renderCarousel();

      if (restartTimer) startAutoPlay();
    }

    cards.forEach((card, index) => {
      card.addEventListener("click", () => {
        const position = card.dataset.carouselPosition;

        if (position === "prev") {
          goTo(index, "prev");
        } else if (position === "next") {
          goTo(index, "next");
        }
      });
    });

    if (dotsContainer) {
      cards.forEach((_, index) => {
        const dot = document.createElement("button");
        dot.type = "button";
        dot.className = "testimonials__dot";
        dot.addEventListener("click", () => {
          const forwardDistance = normalizedIndex(index - currentIndex);
          const direction = forwardDistance <= cards.length / 2 ? "next" : "prev";
          goTo(index, direction);
        });
        dotsContainer.appendChild(dot);
        dots.push(dot);
      });
    }

    previousButton?.addEventListener("click", () => {
      goTo(currentIndex - 1, "prev");
    });

    nextButton?.addEventListener("click", () => {
      goTo(currentIndex + 1, "next");
    });

    stage.addEventListener("keydown", (event) => {
      if (event.key === "ArrowLeft") {
        event.preventDefault();
        goTo(currentIndex - 1, "prev");
      } else if (event.key === "ArrowRight") {
        event.preventDefault();
        goTo(currentIndex + 1, "next");
      }
    });

    stage.addEventListener(
      "touchstart",
      (event) => {
        touchStartX = event.changedTouches[0]?.clientX ?? null;
      },
      { passive: true },
    );

    stage.addEventListener(
      "touchend",
      (event) => {
        if (touchStartX === null) return;

        const endX = event.changedTouches[0]?.clientX ?? touchStartX;
        const distance = endX - touchStartX;
        touchStartX = null;

        if (Math.abs(distance) < 42) return;

        if (distance < 0) {
          goTo(currentIndex + 1, "next");
        } else {
          goTo(currentIndex - 1, "prev");
        }
      },
      { passive: true },
    );

    if ("IntersectionObserver" in window) {
      const sectionObserver = new IntersectionObserver(
        (entries) => {
          sectionIsVisible = entries.some((entry) => entry.isIntersecting);

          if (sectionIsVisible) {
            startAutoPlay();
          } else {
            stopAutoPlay();
          }
        },
        {
          threshold: 0.22,
        },
      );

      sectionObserver.observe(section);
    }

    document.addEventListener("visibilitychange", () => {
      if (document.hidden) {
        stopAutoPlay();
      } else {
        startAutoPlay();
      }
    });

    const directionObserver = new MutationObserver(() => {
      updateControlLabels();
    });

    directionObserver.observe(document.documentElement, {
      attributes: true,
      attributeFilter: ["lang", "dir"],
    });

    updateControlLabels();
    renderCarousel();
    startAutoPlay();
  }

  if (document.readyState === "loading") {
    document.addEventListener(
      "DOMContentLoaded",
      initializeTestimonialsCarousel,
      { once: true },
    );
  } else {
    initializeTestimonialsCarousel();
  }
})();


