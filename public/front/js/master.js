const LANGUAGE_STORAGE_KEY = "palprints-language-v3";

const textBindings = [];
const attributeBindings = [];

function normalizeText(value) {
  return value.trim().replace(/\s+/g, " ");
}

function initializeTranslations() {
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const parentTag = node.parentElement?.tagName;
        if (!parentTag || parentTag === "SCRIPT" || parentTag === "STYLE") {
          return NodeFilter.FILTER_REJECT;
        }

        const key = normalizeText(node.nodeValue || "");
        return Object.prototype.hasOwnProperty.call(translations, key)
          ? NodeFilter.FILTER_ACCEPT
          : NodeFilter.FILTER_REJECT;
      }
    }
  );

  let currentNode;
  while ((currentNode = walker.nextNode())) {
    const originalValue = currentNode.nodeValue || "";
    textBindings.push({
      node: currentNode,
      key: normalizeText(originalValue),
      prefix: originalValue.match(/^\s*/)?.[0] || "",
      suffix: originalValue.match(/\s*$/)?.[0] || ""
    });
  }

  document.querySelectorAll("[alt], [aria-label], [title], [placeholder]").forEach((element) => {
    ["alt", "aria-label", "title", "placeholder"].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;

      const key = normalizeText(element.getAttribute(attribute) || "");
      if (Object.prototype.hasOwnProperty.call(translations, key)) {
        attributeBindings.push({ element, attribute, key });
      }
    });
  });
}

function applyLanguage(language, savePreference = true) {
  const selectedLanguage = language === "en" ? "en" : "ar";
  const htmlTag = document.documentElement;

  htmlTag.setAttribute("lang", selectedLanguage);
  htmlTag.setAttribute("dir", selectedLanguage === "ar" ? "rtl" : "ltr");

  textBindings.forEach(({ node, key, prefix, suffix }) => {
    const translatedText = selectedLanguage === "en" ? translations[key] : key;
    node.nodeValue = `${prefix}${translatedText}${suffix}`;
  });

  attributeBindings.forEach(({ element, attribute, key }) => {
    element.setAttribute(attribute, selectedLanguage === "en" ? translations[key] : key);
  });

  // اجعل زري اللغة في الهيدر والفوتر يعرضان اللغة التي سينتقل إليها المستخدم
  const languageButtonLabel = selectedLanguage === "ar" ? "English" : "العربية";

  const langText = document.getElementById("lang-text");
  if (langText) {
    langText.textContent = languageButtonLabel;
  }

  const footerLangText = document.querySelector("#footer-lang-toggle span");
  if (footerLangText) {
    footerLangText.textContent = languageButtonLabel;
  }

  if (savePreference) {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, selectedLanguage);
  }
}

function toggleLanguage() {
  const currentLanguage = document.documentElement.lang === "en" ? "en" : "ar";
  applyLanguage(currentLanguage === "ar" ? "en" : "ar");
}

document.addEventListener("DOMContentLoaded", () => {
  // 1. Bootstrap Icons are loaded through CSS; no runtime initialization is needed.

// 2. تجهيز الترجمة وبدء الصفحة بالعربية دائماً
  initializeTranslations();
  localStorage.setItem(LANGUAGE_STORAGE_KEY, "ar");
  applyLanguage("ar", false);

  // 3. إدارة قائمة الموبايل
  const hamburger = document.getElementById("hamburger");
  const navMenu = document.getElementById("navMenu");
  const navLinks = document.querySelectorAll(".nav-link");
  const mobileMenuClose = document.querySelector(".navbar__menu-close");
  const overlay = document.createElement("div");

  overlay.className = "navbar-overlay";

  // Keep the dimmer in the same stacking context as the header. The hero shell
  // is isolated for its background, so an overlay appended to <body> would sit
  // above the whole header and hide the mobile drawer.
  const overlayHost = document.querySelector(".hero-shell") || document.body;
  overlayHost.appendChild(overlay);

  function openMobileMenu() {
    if (!navMenu) return;
    navMenu.classList.add("mobile-open");
    overlay.classList.add("active");
    document.body.classList.add("mobile-menu-open");
    document.body.style.overflow = "hidden";
    hamburger?.setAttribute("aria-expanded", "true");
    hamburger?.setAttribute(
      "aria-label",
      document.documentElement.lang === "en" ? "Close menu" : "إغلاق القائمة",
    );
    const hamburgerIcon = hamburger?.querySelector("i");
    if (hamburgerIcon) hamburgerIcon.className = "bi bi-x-lg";
    window.setTimeout(() => mobileMenuClose?.focus(), 80);
  }

  function closeMobileMenu() {
    if (!navMenu) return;
    navMenu.classList.remove("mobile-open");
    overlay.classList.remove("active");
    document.body.classList.remove("mobile-menu-open");
    document.body.style.overflow = "";
    hamburger?.setAttribute("aria-expanded", "false");
    hamburger?.setAttribute(
      "aria-label",
      document.documentElement.lang === "en" ? "Open menu" : "فتح القائمة",
    );
    const hamburgerIcon = hamburger?.querySelector("i");
    if (hamburgerIcon) hamburgerIcon.className = "bi bi-list";
  }

  hamburger?.addEventListener("click", () => {
    if (!navMenu) return;
    navMenu.classList.contains("mobile-open") ? closeMobileMenu() : openMobileMenu();
  });

  overlay.addEventListener("click", closeMobileMenu);
  mobileMenuClose?.addEventListener("click", () => {
    closeMobileMenu();
    hamburger?.focus();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && navMenu?.classList.contains("mobile-open")) {
      closeMobileMenu();
    }
  });

  navLinks.forEach((link) => {
    link.addEventListener("click", function () {
      navLinks.forEach((item) => item.classList.remove("active"));
      this.classList.add("active");
      if (window.innerWidth <= 768) closeMobileMenu();
    });
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 768 && navMenu?.classList.contains("mobile-open")) {
      closeMobileMenu();
    }
  });

  // 4. مزامنة مظهر الصفحة تلقائيًا مع الوضع المختار في الجهاز.
  const deviceTheme = window.matchMedia("(prefers-color-scheme: dark)");

  function applyDeviceTheme(event) {
    const isDark = event.matches;
    document.body.classList.toggle("dark-mode", isDark);
    document.documentElement.dataset.bsTheme = isDark ? "dark" : "light";
  }

  applyDeviceTheme(deviceTheme);
  deviceTheme.addEventListener?.("change", applyDeviceTheme);

  // 5. ربط زر اللغة الموجود في الفوتر بنفس نظام الترجمة
  const footerLanguageButton = document.getElementById("footer-lang-toggle");
  footerLanguageButton?.addEventListener("click", toggleLanguage);

  document
    .querySelector('[data-mobile-action="language"]')
    ?.addEventListener("click", () => {
      toggleLanguage();
      closeMobileMenu();
    });

  function openDesignSearch(delay = 0) {
    window.setTimeout(() => {
      const searchField = document.getElementById("design-category-search");
      if (!searchField) return;

      searchField.scrollIntoView({ behavior: "smooth", block: "center" });

      window.setTimeout(() => {
        searchField.focus({ preventScroll: true });
      }, 380);
    }, delay);
  }

  document
    .querySelector(".header-search-btn")
    ?.addEventListener("click", () => openDesignSearch());

  document
    .querySelector('[data-mobile-action="search"]')
    ?.addEventListener("click", () => {
      closeMobileMenu();
      openDesignSearch(340);
    });

  // 6. البحث داخل فئات التصاميم الجديدة
  const designSearchForm = document.querySelector(".design-discovery__search");
  const designSearchInput = document.querySelector(
    ".design-discovery__search-input",
  );
  const designCategoryCards = Array.from(
    document.querySelectorAll(".design-category-card"),
  );
  const designSearchEmpty = document.querySelector(
    ".design-discovery__no-results",
  );

  function normalizeDesignSearch(value) {
    return value
      .toLocaleLowerCase()
      .normalize("NFKD")
      .replace(/[\u064b-\u065f\u0670]/g, "")
      .trim();
  }

  function filterDesignCategories() {
    const query = normalizeDesignSearch(designSearchInput?.value || "");
    let visibleCards = 0;

    designCategoryCards.forEach((card) => {
      const searchTerms = normalizeDesignSearch(card.dataset.search || "");
      const matches = !query || searchTerms.includes(query);

      card.hidden = !matches;
      if (matches) visibleCards += 1;
    });

    if (designSearchEmpty) {
      designSearchEmpty.hidden = visibleCards !== 0;
    }
  }

  designSearchForm?.addEventListener("submit", (event) => {
    event.preventDefault();
    filterDesignCategories();
  });

  designSearchInput?.addEventListener("input", filterDesignCategories);
  designSearchInput?.addEventListener("keydown", (event) => {
    if (event.key !== "Escape") return;
    designSearchInput.value = "";
    filterDesignCategories();
  });
});



